import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { Experience, Goal, Gym, Program } from '../../src/db/types';
import { requireExercise } from '../../src/domain/catalog';
import { estimateDayMinutes, generateProgram, goalName, programFromTemplate, type ProgramReport } from '../../src/domain/generator';
import { createGymFromCatalog, createGymFromPreset, loadSourceFor } from '../../src/domain/gym';
import { describeLoad } from '../../src/domain/loads';
import { startingLoad } from '../../src/domain/resolver';
import { muscleName } from '../../src/domain/volume';

/**
 * Writes docs/program-samples.md so generated programs can be reviewed by a person, the way a
 * coach would check them. Run with: ATLAS_PREVIEW=1 npx vitest run tests/domain/preview.test.ts
 */

const DAYS = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];

function render(title: string, program: Program, report: ProgramReport, gym: Gym, experience: Experience): string {
  const lines = [`## ${title}`, ''];
  lines.push(`**Week:** ${program.schedule.map((id, i) => `${DAYS[i]} ${id ? program.days.find((d) => d.id === id)?.name : 'rest'}`).join(' · ')}`);
  lines.push(`**Block:** ${program.block.lengthWeeks} weeks, then a lighter week`, '');
  for (const day of program.days) {
    lines.push(`### ${day.name}: ${day.subtitle ?? ''} (about ${estimateDayMinutes(day)} min)`, '');
    lines.push('| Exercise | Sets × reps | Reps left | Rest | First-time start |', '|---|---|---|---|---|');
    for (const slot of day.slots) {
      const exercise = requireExercise(slot.exerciseId);
      const unit = exercise.metric === 'time' ? ' s' : exercise.unilateral ? ' each side' : '';
      const reps = slot.repsLow === slot.repsHigh ? `${slot.repsLow}` : `${slot.repsLow}–${slot.repsHigh}`;
      const pair = slot.superset ? ` ⇄${slot.superset.split('-ss')[1]}` : '';
      const start = startingLoad(exercise.id, gym, experience);
      const source = loadSourceFor(exercise, gym);
      const startText = start !== null && source ? `${start} lb (${describeLoad(source.model, start, exercise.loadMode).detail})` : '–';
      lines.push(
        `| ${exercise.name}${pair}${slot.purpose ? `<br><sub>${slot.purpose}</sub>` : ''} | ${slot.sets} × ${reps}${unit} | ${slot.rir} | ${Math.round((slot.restSec ?? 0) / 15) * 15} s | ${startText} |`,
      );
    }
    for (const extra of day.extras ?? []) lines.push(`| + ${extra.label}${extra.detail ? ` (${extra.detail})` : ''}: ${requireExercise(extra.exerciseId).name} | | | | |`);
    lines.push('');
  }
  const sets = Object.entries(report.weeklySets)
    .filter(([, v]) => (v ?? 0) >= 1)
    .sort((a, b) => (b[1] ?? 0) - (a[1] ?? 0))
    .map(([m, v]) => `${muscleName(m as never)} ${v}`);
  lines.push(`**Weekly sets per muscle:** ${sets.join(' · ')}`, '');
  if (report.notes.length) lines.push(`**Notes:** ${report.notes.join(' ')}`, '');
  return lines.join('\n');
}

describe('program samples', () => {
  it.runIf(process.env.ATLAS_PREVIEW)('writes docs/program-samples.md', () => {
    const office = createGymFromPreset('office');
    const barbellGym = createGymFromCatalog('Commercial gym', [
      'barbell-and-plates', 'squat-rack', 'adjustable-bench', 'dumbbells-5-100', 'dual-cable-machine', 'dip-station',
      'pull-up-bar', 'lat-pulldown-machine', 'seated-row-machine', 'leg-press-machine', 'leg-curl-machine',
      'leg-extension-machine', 'calf-raise-machine', 'treadmill', 'exercise-bike',
    ]);
    const parts = [
      '# Program samples',
      '',
      'Generated by `ATLAS_PREVIEW=1 npx vitest run tests/domain/preview.test.ts` for review. "First-time start" is the conservative calibration guess; the first set corrects it. ⇄ marks two exercises done back to back as a superset.',
      '',
    ];
    const pillar = programFromTemplate('pillar', office, { experience: 'intermediate', goal: 'fat-loss' });
    parts.push(render('Pillar at the Office (intermediate, fat loss)', pillar.program, pillar.report, office, 'intermediate'));

    const cases: [string, Gym, Goal, Experience, number, number][] = [
      ['Office', office, 'muscle', 'intermediate', 4, 60],
      ['Office', office, 'fat-loss', 'beginner', 3, 45],
      ['Office', office, 'general', 'beginner', 2, 30],
      ['Commercial gym', barbellGym, 'strength', 'advanced', 4, 75],
      ['Office', office, 'muscle', 'advanced', 6, 60],
    ];
    for (const [gymName, gym, goal, experience, days, minutes] of cases) {
      const built = generateProgram({ goal, experience, daysPerWeek: days, sessionMinutes: minutes }, gym, 0);
      parts.push(render(`${goalName(goal)}: ${experience}, ${days} days, ${minutes} min, ${gymName}`, built.program, built.report, gym, experience));
    }
    writeFileSync(new URL('../../docs/program-samples.md', import.meta.url), parts.join('\n'));
    expect(parts.length).toBeGreaterThan(4);
  });
});
